#!/usr/bin/env python3
"""nostalre-client's job tables (lib/game/src/job_tables.rs) from rAthena's Renewal job data.

Which jobs have AP (a `BaseAp` in db/re/job_basepoints.yml) and each job's highest base level (`MaxBaseLevel` in
db/re/job_exp.yml, else `MAX_LEVEL` of src/map/map.hpp), by the ids of rAthena's `e_job`.

Usage: job-tables.py [rathena dir] [output file]
"""

import sys
import re
from pathlib import Path

from rathena_data import load_body, parse_enum

ROOT = Path(__file__).resolve().parent.parent
RATHENA = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "server"
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "client" / "lib" / "game" / "src" / "job_tables.rs"


def main():
    ids = parse_enum(RATHENA / "src/common/mmo.hpp", "enum e_job", "JOB_")
    jobs = set()
    for entry in load_body(RATHENA / "db" / "re" / "job_basepoints.yml"):
        if entry.get("BaseAp"):
            jobs.update(ids["JOB_" + name.upper()] for name in entry["Jobs"])
    jobs = sorted(jobs)
    default = int(re.search(r"#define MAX_LEVEL (\d+)", (RATHENA / "src/map/map.hpp").read_text()).group(1))
    max_levels = {}
    for entry in load_body(RATHENA / "db" / "re" / "job_exp.yml"):
        if "MaxBaseLevel" in entry:
            for name in entry["Jobs"]:
                max_levels.setdefault(entry["MaxBaseLevel"], set()).add(ids["JOB_" + name.upper()])
    arms = [
        f"        {' | '.join(str(j) for j in sorted(js))} => {level},"
        for level, js in sorted(max_levels.items())
        if level != default
    ]
    lines = [
        "// Generated by scripts/job-tables.py from rAthena's db/re/job_basepoints.yml and job_exp.yml; do not edit.",
        "",
        "/// The jobs with AP (a `BaseAp`), rAthena's `e_job` ids",
        "pub fn has_ap(job: u16) -> bool {",
        f"    matches!(job, {' | '.join(str(j) for j in jobs)})",
        "}",
        "",
        "/// A job's highest base level (`MaxBaseLevel`, else `MAX_LEVEL`), by rAthena's `e_job` id",
        "pub fn max_base_level(job: u16) -> u16 {",
        "    match job {",
        *arms,
        f"        _ => {default},",
        "    }",
        "}",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({len(jobs)} jobs)")


if __name__ == "__main__":
    main()
