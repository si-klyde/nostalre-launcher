#!/usr/bin/env python3
"""nostalre-client's `SkillEnum` (rust-ro/models/src/enums/skill_enums.rs) from rAthena's skill db.

Also the server's flags the client mirrors (`FLAGS`), each a `matches!` over the skills that have it, so a
client-side rule never drifts from the server's data.

Every skill of db/re/skill_db.yml, then the few of db/pre-re that Renewal dropped (rust-ro's enum had them, and the
effect and sound tables still name them). A variant is the aegis name in PascalCase (NV_BASIC is NvBasic), as
rust-ro's generator named them.

Usage: skill-enum.py [rathena dir] [output file]
"""

import sys
from collections import Counter
from functools import cache
from pathlib import Path

from rathena_data import load_body, parse_enum, skill_variant as variant

ROOT = Path(__file__).resolve().parent.parent
RATHENA = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "server"
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "client" / "rust-ro" / "models" / "src" / "enums" / "skill_enums.rs"


# skill_db flag -> the generated method telling whether a skill has it
FLAGS = {
    "AllowWhenHidden": "allowed_when_hidden",
    "IsGuild": "is_guild",
    "IsSong": "is_song",
    "IsEnsemble": "is_ensemble",
}


@cache
def skill_db(mode):
    return load_body(RATHENA / "db" / mode / "skill_db.yml")


def skills():
    """(id, aegis name, description, flags) of every skill, by id; Renewal's entry wins an id both dbs have."""
    by_id = {}
    for mode in ("pre-re", "re"):
        for entry in skill_db(mode):
            flags = frozenset(f for f, on in (entry.get("Flags") or {}).items() if on)
            by_id[entry["Id"]] = (entry["Id"], entry["Name"], entry.get("Description", entry["Name"]), flags)
    result = sorted(by_id.values())
    duplicates = [v for v, n in Counter(variant(name) for _, name, _, _ in result).items() if n > 1]
    if duplicates:
        sys.exit(f"one variant for two skills: {sorted(duplicates)}")
    return result


def trap_units():
    """(unit id, unit name) of every unit an `IsTrap` skill lays, Renewal's db."""
    ids = parse_enum(RATHENA / "src/map/skill.hpp", "enum e_skill_unit_id", "UNT_")
    units = set()
    for entry in skill_db("re"):
        unit = entry.get("Unit") or {}
        if (entry.get("Flags") or {}).get("IsTrap"):
            for key in ("Id", "AlternateId"):
                if unit.get(key):
                    name = f"UNT_{unit[key].upper()}"
                    units.add((ids[name], name))
    return sorted(units)


def main():
    rows = skills()
    lines = [
        "// Generated by scripts/skill-enum.py from rAthena's db/re/skill_db.yml (and db/pre-re's skills Renewal",
        "// dropped); do not edit.",
        "",
        "#[derive(Clone, Copy, PartialEq, Debug)]",
        "pub enum SkillEnum {",
    ]
    for _, name, description, _ in rows:
        lines.append(f"    // {description}")
        lines.append(f"    {variant(name)},")
    lines.append("}")
    lines.append("")
    lines.append("impl SkillEnum {")
    lines.append(f"    pub const ALL: [SkillEnum; {len(rows)}] = [")
    lines += [f"        Self::{variant(name)}," for _, name, _, _ in rows]
    lines.append("    ];")
    lines.append("")

    def method(signature, scrutinee, arms, fallback=None):
        lines.append(f"    {signature} {{")
        lines.append(f"        match {scrutinee} {{")
        lines.extend(f"            {arm}," for arm in arms)
        if fallback:
            lines.append(f"            {fallback},")
        lines.append("        }")
        lines.append("    }")
        lines.append("")

    method("pub fn id(&self) -> u32", "self", [f"Self::{variant(n)} => {i}" for i, n, _, _ in rows])
    method(
        "pub fn try_from_value(id: u32) -> Result<Self, String>",
        "id",
        [f"{i} => Ok(Self::{variant(n)})" for i, n, _, _ in rows],
        '_ => Err(format!("unknown skill id {id}"))',
    )
    method("pub fn to_name(&self) -> &'static str", "self", [f'Self::{variant(n)} => "{n}"' for _, n, _, _ in rows])
    for flag, name in FLAGS.items():
        having = [f"Self::{variant(n)}" for _, n, _, flags in rows if flag in flags]
        if not having:
            sys.exit(f"no skill has {flag}: an empty matches! would not compile")
        lines.append(f"    /// skill_db's `{flag}`")
        lines.append(f"    pub fn {name}(&self) -> bool {{")
        lines.append(f"        matches!(self, {' | '.join(having)})")
        lines.append("    }")
        lines.append("")
    lines[-1:] = ["}", ""]
    traps = trap_units()
    lines.append("/// The ground units a skill_db `IsTrap` skill lays (rAthena's `e_skill_unit_id`): what Remove Trap")
    lines.append("/// and the trap rules apply to.")
    lines.append("pub fn is_trap_unit(unit_id: u16) -> bool {")
    lines.append(f"    matches!(unit_id, {' | '.join(f'0x{i:x}' for i, _ in traps)})")
    lines.append("}")
    lines.append("")
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({len(rows)} skills)")


if __name__ == "__main__":
    main()
