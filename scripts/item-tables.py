#!/usr/bin/env python3
"""nostalre-client's item tables (lib/game/src/item_tables.rs) from rAthena's Renewal item db.

What the client needs when kRO's iteminfo does not know an item (one newer than the client's data): the weapon view a
weapon draws with (its `SubType` as rAthena's `weapon_type`, the view ids of kRO's weapontable) and which items are
shields. Read from the server's data so the two never disagree.

Usage: item-tables.py [rathena dir] [output file]
"""

import sys
from pathlib import Path

from rathena_data import load_body, parse_enum

ROOT = Path(__file__).resolve().parent.parent
RATHENA = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "server"
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "client" / "lib" / "game" / "src" / "item_tables.rs"
PER_LINE = 8


def rows(values, per_line=PER_LINE):
    """Lines of the array's entries: a pair as a tuple, anything else as it is."""
    cells = [f"({v[0]}, {v[1]})" if isinstance(v, tuple) else str(v) for v in values]
    return [" ".join(c + "," for c in cells[i : i + per_line]) for i in range(0, len(cells), per_line)]


def main():
    types = parse_enum(RATHENA / "src/map/pc.hpp", "enum weapon_type", "W_")
    weapons, shields = [], []
    for item in load_body(RATHENA / "db" / "re" / "item_db_equip.yml"):
        if item.get("Type") == "Weapon" and item.get("SubType"):
            weapons.append((item["Id"], types["W_" + item["SubType"].upper()]))
        elif item.get("Type") == "Armor" and (item.get("Locations") or {}).get("Left_Hand"):
            shields.append(item["Id"])
    weapons.sort()
    shields.sort()
    lines = [
        "// Generated by scripts/item-tables.py from rAthena's db/re/item_db_equip.yml; do not edit.",
        "",
        "/// (item id, weapon view): a weapon's `SubType` as rAthena's `weapon_type`, the view ids of kRO's weapontable",
        f"static WEAPON_VIEWS: [(u32, u16); {len(weapons)}] = [",
    ]
    lines += ["    " + row for row in rows(weapons)]
    lines += [
        "];",
        "",
        "/// Items worn in the left hand that are not weapons",
        f"static SHIELDS: [u32; {len(shields)}] = [",
    ]
    lines += ["    " + row for row in rows(shields, PER_LINE * 2)]
    lines += [
        "];",
        "",
        "/// The weapon view rAthena's item db gives a weapon, `None` for anything else",
        "pub fn item_weapon_view(item_id: u32) -> Option<u16> {",
        "    WEAPON_VIEWS.binary_search_by_key(&item_id, |&(id, _)| id).ok().map(|i| WEAPON_VIEWS[i].1)",
        "}",
        "",
        "/// Whether rAthena's item db has the item as a shield",
        "pub fn item_is_shield(item_id: u32) -> bool {",
        "    SHIELDS.binary_search(&item_id).is_ok()",
        "}",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({len(weapons)} weapons, {len(shields)} shields)")


if __name__ == "__main__":
    main()
