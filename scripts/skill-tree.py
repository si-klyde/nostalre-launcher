#!/usr/bin/env python3
"""nostalre-client's skill tree table (lib/game/src/skill_tree_tables.rs) from rAthena's db/re/skill_tree.yml.

Each job's own tree and the jobs it inherits, as rAthena's `SkillTreeDatabase::parseBodyNode` reads them: a job
listed twice adds to its first entry, a skill listed twice updates it, a `Requires` level of 0 drops that
requirement, levels above the skill's `MaxLevel` in db/re/skill_db.yml are capped. The client merges the inherited
trees as `loadingFinished` does (`ragnarok_game::skill_tree`).

Usage: skill-tree.py [rathena dir] [output file]
"""

import re
import sys
from pathlib import Path

from rathena_data import load_body, parse_enum, skill_variant

ROOT = Path(__file__).resolve().parent.parent
RATHENA = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "server"
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "client" / "lib" / "game" / "src" / "skill_tree_tables.rs"


def main():
    ids = parse_enum(RATHENA / "src/common/mmo.hpp", "enum e_job", "JOB_")
    # script_get_constant ignores case and knows the aliases of script_constants.hpp ("Job_SuperNovice")
    constants = (RATHENA / "src/map/script_constants.hpp").read_text()
    aliases = re.findall(r'export_constant2\("(JOB_\w+)",\s*(JOB_\w+)\)', constants, re.I)
    ids.update({alias.upper(): ids[target] for alias, target in aliases})
    skill_max = {s["Name"]: s.get("MaxLevel", 1) for s in load_body(RATHENA / "db" / "re" / "skill_db.yml")}
    jobs = {}
    for node in load_body(RATHENA / "db" / "re" / "skill_tree.yml"):
        job = ids["JOB_" + node["Job"].upper()]
        tree = jobs.setdefault(job, {"inherit": [], "skills": {}})
        for name, active in (node.get("Inherit") or {}).items():
            other = ids["JOB_" + name.upper()]
            if active and other not in tree["inherit"]:
                tree["inherit"].append(other)
            elif not active and other in tree["inherit"]:
                tree["inherit"].remove(other)
        for entry in node.get("Tree") or []:
            name = entry["Name"]
            skill = tree["skills"].setdefault(
                name, {"max": 0, "base": 0, "job": 0, "exclude": False, "needs": {}}
            )
            skill["max"] = min(entry["MaxLevel"], skill_max[name])
            skill["base"] = entry.get("BaseLevel", skill["base"])
            skill["job"] = entry.get("JobLevel", skill["job"])
            skill["exclude"] = entry.get("Exclude", skill["exclude"])
            for need in entry.get("Requires") or []:
                level = min(need["Level"], skill_max[need["Name"]])
                if level == 0:
                    skill["needs"].pop(need["Name"], None)
                else:
                    skill["needs"][need["Name"]] = level

    lines = [
        "// Generated by scripts/skill-tree.py from rAthena's db/re/skill_tree.yml; do not edit.",
        "",
        "use crate::skill::SkillEnum;",
        "",
        "/// One skill of a job's own tree, as rAthena's `s_skill_tree_entry` holds it",
        "pub struct TreeEntry {",
        "    pub skill: SkillEnum,",
        "    pub max_level: u8,",
        "    pub base_level: u16,",
        "    pub job_level: u16,",
        "    /// Not passed on to the jobs that inherit this one",
        "    pub exclude: bool,",
        "    /// The skills and levels it needs",
        "    pub requires: &'static [(SkillEnum, u8)],",
        "}",
        "",
    ]
    for job, tree in sorted(jobs.items()):
        lines.append(f"const TREE_{job}: &[TreeEntry] = &[")
        for name, s in tree["skills"].items():
            needs = ", ".join(f"(SkillEnum::{skill_variant(n)}, {lv})" for n, lv in s["needs"].items())
            lines.append(
                f"    TreeEntry {{ skill: SkillEnum::{skill_variant(name)}, max_level: {s['max']}, "
                f"base_level: {s['base']}, job_level: {s['job']}, exclude: {str(s['exclude']).lower()}, "
                f"requires: &[{needs}] }},"
            )
        lines += ["];", ""]
    lines += [
        "/// A job's own tree, by rAthena's `e_job` id, in the database's order",
        "pub fn own_tree(job: u16) -> &'static [TreeEntry] {",
        "    match job {",
        *[f"        {job} => TREE_{job}," for job in sorted(jobs)],
        "        _ => &[],",
        "    }",
        "}",
        "",
        "/// The jobs whose trees a job inherits, in the database's order",
        "pub fn inherits(job: u16) -> &'static [u16] {",
        "    match job {",
        *[
            f"        {job} => &[{', '.join(str(j) for j in tree['inherit'])}],"
            for job, tree in sorted(jobs.items())
            if tree["inherit"]
        ],
        "        _ => &[],",
        "    }",
        "}",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({len(jobs)} jobs)")


if __name__ == "__main__":
    main()
