#!/usr/bin/env python3
"""The Android hub's job names and Doram jobs (android/app/src/main/java/io/github/siklyde/nostalre/JobNames.kt) from rAthena.

rAthena names a job with `job_name()` (src/map/pc.cpp): a switch from the `e_job` id to a line of
conf/msg_conf/map_msg.conf, either fixed (`msg_txt(nullptr,563)`) or counted from the case's first job
(`msg_txt(nullptr,557 - JOB_KNIGHT+class_)`). This follows the same switch for every job it names.

Usage: job-names.py [rathena dir] [output file]
"""

import re
import sys
from pathlib import Path

from rathena_data import parse_enum

ROOT = Path(__file__).resolve().parent.parent
RATHENA = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "server"
OUT = (
    Path(sys.argv[2])
    if len(sys.argv) > 2
    else ROOT / "android" / "app" / "src" / "main" / "java" / "io" / "github" / "siklyde" / "nostalre" / "JobNames.kt"
)


def messages():
    lines = {}
    for line in (RATHENA / "conf" / "msg_conf" / "map_msg.conf").read_text(encoding="utf-8", errors="replace").splitlines():
        m = re.match(r"(\d+):\s*(.*)$", line)
        if m:
            lines[int(m.group(1))] = m.group(2).strip()
    return lines


def job_name_switch():
    text = (RATHENA / "src" / "map" / "pc.cpp").read_text()
    start = text.index("const char* job_name(int32 class_)")
    body = text[start : text.index("\n}\n", start)]
    return body


def mapids():
    """MAPID_ name -> value of rAthena's `e_mapid` (src/map/map.hpp), whose entries combine `JOBL_` flags."""
    text = (RATHENA / "src" / "map" / "map.hpp").read_text()
    flags = {m.group(1): int(m.group(2), 0) for m in re.finditer(r"#define (JOBL_\w+|MAPID_\w+MASK) (0x[0-9a-fA-F]+|\d+)", text)}
    flags["UINT64_MAX"] = 2**64 - 1
    start = re.search(r"enum e_mapid\b[^{]*\{", text).end()
    values, value = {}, -1
    for line in text[start : text.index("};", start)].splitlines():
        m = re.match(r"\s*(MAPID_\w+)\s*(?:=\s*([^,/]+?))?\s*,?\s*(?://.*)?$", line)
        if not m:
            continue
        if m.group(2) is None:
            value += 1
        else:
            value = 0
            for part in m.group(2).split("|"):
                part = part.strip()
                value |= flags[part] if part in flags else values[part] if part in values else int(part, 0)
        values[m.group(1)] = value
    return values, flags


def doram_jobs(ids):
    """The jobs pc_jobid2mapid() (src/map/pc.cpp) puts in the Summoner's first class: rAthena's test for a Doram."""
    values, flags = mapids()
    text = (RATHENA / "src" / "map" / "pc.cpp").read_text()
    start = text.index("uint64 pc_jobid2mapid(")
    body = text[start : text.index("\n}\n", start)]
    jobs = set()
    for job, mapid in re.findall(r"case\s+(JOB_\w+)\s*:\s*return\s+(MAPID_\w+)\s*;", body):
        if values[mapid] & flags["MAPID_FIRSTMASK"] == values["MAPID_SUMMONER"]:
            jobs.add(ids[job])
    return sorted(jobs)


def main():
    ids = parse_enum(RATHENA / "src/common/mmo.hpp", "enum e_job", "JOB_")
    msg = messages()
    names, cases = {}, []
    for line in job_name_switch().splitlines():
        case = re.match(r"\s*case\s+(JOB_\w+)\s*:", line)
        if case:
            cases.append(case.group(1))
            continue
        ret = re.search(r"return\s+msg_txt\(\s*nullptr\s*,\s*(\d+)\s*(?:-\s*(JOB_\w+)\s*\+\s*class_)?\s*\)", line)
        if ret:
            base, first = int(ret.group(1)), ret.group(2)
            for name in cases:
                line_id = base - ids[first] + ids[name] if first else base
                names[ids[name]] = msg[line_id]
            cases = []
        elif re.search(r"\bdefault\s*:", line):
            cases = []
    doram = ", ".join(str(job) for job in doram_jobs(ids))
    rows = "\n".join(f'\t\t{job} to "{names[job]}",' for job in sorted(names))
    OUT.write_text(
        f"""// Generated by scripts/job-names.py from rAthena's job_name() (src/map/pc.cpp) and conf/msg_conf/map_msg.conf.
// Do not edit: rerun the script.
package io.github.siklyde.nostalre

/** Job names by rAthena class id, as the server names them. */
object JobNames {{
\tval NAMES = mapOf(
{rows}
\t)

\t/** Doram jobs: pc_jobid2mapid() gives them the Summoner's first class. */
\tval DORAM = setOf( {doram} )
}}
"""
    )
    print(f"{OUT}: {len(names)} jobs")


if __name__ == "__main__":
    main()
